# 把一团蒸汽，变成持续的转动

可以把蒸汽机想成一套不断重复的动作：**烧水、推动、换向，再推动**。真正推动活塞的是气缸两侧的压力差，连杆则把往复运动变成车轮转动。

## 一次循环里发生了什么？

1. **产生蒸汽。** 燃料在锅炉外部燃烧，把锅炉里的水加热成高压蒸汽。
2. **推动活塞。** 阀门让蒸汽进入气缸的一侧，活塞被推向另一端。
3. **切换方向。** 阀门改变进汽和排汽的路径，活塞回程。
4. **带动车轮。** 连杆和曲柄把来回运动转成旋转，飞轮帮助运动保持平稳。

## 为什么它叫「外燃机」？

