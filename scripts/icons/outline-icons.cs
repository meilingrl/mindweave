// Turns the stroked icon source into the filled outlines Avalonia's PathIcon draws.
//
//   dotnet run scripts/icons/outline-icons.cs            rewrite the generated block of Icons.axaml
//   dotnet run scripts/icons/outline-icons.cs -- --check  exit 1 if Icons.axaml is not what this would write
//
// Source: src/Mindweave.Desktop/Themes/IconStrokes.xml (centre-line SVG elements on a 16 × 16 grid).
// Output: the block between the "generated" markers in src/Mindweave.Desktop/Themes/Icons.axaml. Anything outside
// the markers is kept as written, so a hand-made icon can sit there until it is redrawn in the source.
//
// Each icon's strokes are widened with round caps and round joins (SKPaint.GetFillPath, the same Skia stroker that
// would draw them on screen), unioned with its solid elements and simplified into non-overlapping contours, so the
// result fills correctly with either fill rule and does not darken where strokes cross.
#:package SkiaSharp@3.119.4
#:property ManagePackageVersionsCentrally=false
#:property TreatWarningsAsErrors=false
#:property AnalysisMode=None
#:property PublishAot=false

using System.Globalization;
using System.Security.Cryptography;
using System.Text;
using System.Text.RegularExpressions;
using System.Xml;
using SkiaSharp;

var root = FindRoot(Directory.GetCurrentDirectory());
var sourcePath = Path.Combine(root, "src", "Mindweave.Desktop", "Themes", "IconStrokes.xml");
var targetPath = Path.Combine(root, "src", "Mindweave.Desktop", "Themes", "Icons.axaml");
var check = args.Contains("--check");

const string Begin = "<!-- BEGIN generated by scripts/icons/outline-icons.cs from IconStrokes.xml";
const string End = "<!-- END generated -->";

var sourceText = File.ReadAllText(sourcePath).ReplaceLineEndings("\n");
var document = new XmlDocument { PreserveWhitespace = false };
document.LoadXml(sourceText);
var icons = document.DocumentElement!;
var defaultStroke = Number(icons.GetAttribute("stroke"));
var byKey = icons.ChildNodes.OfType<XmlElement>().ToDictionary(e => e.GetAttribute("key"));

var block = new StringBuilder();
block.Append(Begin).Append(" (sha256 ").Append(Hash(sourceText)).Append("). Do not edit by hand. -->\n");
foreach (XmlNode node in icons.ChildNodes)
{
    switch (node)
    {
        case XmlComment comment:
            block.Append("  <!-- ").Append(comment.Value!.Trim()).Append(" -->\n");
            break;
        case XmlElement icon:
            var key = icon.GetAttribute("key");
            var drawing = icon.HasAttribute("like") ? byKey[icon.GetAttribute("like")] : icon;
            var stroke = icon.HasAttribute("stroke") ? Number(icon.GetAttribute("stroke")) : defaultStroke;
            block.Append("  <StreamGeometry x:Key=\"").Append(key).Append("\">")
                .Append(Outline(drawing, stroke)).Append("</StreamGeometry>\n");
            break;
    }
}

block.Append("  ").Append(End);

var target = File.ReadAllText(targetPath).ReplaceLineEndings("\n");
var start = target.IndexOf(Begin, StringComparison.Ordinal);
var end = target.IndexOf(End, StringComparison.Ordinal);
if (start < 0 || end < 0)
{
    Console.Error.WriteLine($"outline-icons: {targetPath} has no generated block; add the BEGIN/END marker comments.");
    return 2;
}

var updated = target[..start] + block + target[(end + End.Length)..];
if (check)
{
    if (updated == target)
    {
        Console.WriteLine("outline-icons: Icons.axaml is up to date.");
        return 0;
    }

    Console.Error.WriteLine("outline-icons: Icons.axaml differs from IconStrokes.xml; run dotnet run scripts/icons/outline-icons.cs");
    return 1;
}

File.WriteAllText(targetPath, updated);
Console.WriteLine($"outline-icons: wrote {byKey.Count} icons to {Path.GetRelativePath(root, targetPath)}.");
return 0;

static string Outline(XmlElement icon, float stroke)
{
    using var strokes = new SKPath();
    using var solids = new SKPath();
    foreach (var element in icon.ChildNodes.OfType<XmlElement>())
    {
        var target = element.GetAttribute("class") == "solid" ? solids : strokes;
        switch (element.Name)
        {
            case "path":
                using (var parsed = SKPath.ParseSvgPathData(element.GetAttribute("d"))
                    ?? throw new FormatException($"{icon.GetAttribute("key")}: bad path {element.GetAttribute("d")}"))
                {
                    target.AddPath(parsed);
                }

                break;
            case "rect":
                var rect = SKRect.Create(Number(element.GetAttribute("x")), Number(element.GetAttribute("y")),
                    Number(element.GetAttribute("width")), Number(element.GetAttribute("height")));
                var rx = element.HasAttribute("rx") ? Number(element.GetAttribute("rx")) : 0;
                target.AddRoundRect(rect, rx, rx);
                break;
            case "circle":
                target.AddCircle(Number(element.GetAttribute("cx")), Number(element.GetAttribute("cy")), Number(element.GetAttribute("r")));
                break;
            default:
                throw new FormatException($"{icon.GetAttribute("key")}: unsupported element <{element.Name}>");
        }
    }

    using var paint = new SKPaint
    {
        IsAntialias = true,
        Style = SKPaintStyle.Stroke,
        StrokeWidth = stroke,
        StrokeCap = SKStrokeCap.Round,
        StrokeJoin = SKStrokeJoin.Round,
    };

    using var widened = new SKPath();
    // A resolution scale of 4 keeps the curve approximation finer than antialiasing shows at 200 % for a 22 px icon.
    paint.GetFillPath(strokes, widened, 4f);
    using var builder = new SKPath.OpBuilder();
    builder.Add(widened, SKPathOp.Union);
    builder.Add(solids, SKPathOp.Union);
    using var result = new SKPath();
    if (!builder.Resolve(result))
    {
        throw new InvalidOperationException($"{icon.GetAttribute("key")}: path union failed");
    }

    // F1 is the non-zero rule; the simplified contours fill the same under either rule.
    var data = Round(result.ToSvgPathData());
    return (result.FillType is SKPathFillType.EvenOdd or SKPathFillType.InverseEvenOdd ? "F0 " : "F1 ") + data;
}

// Two decimals on a 16-unit grid is 0.03 px at 200 % for a 20 px icon: finer than antialiasing can show.
static string Round(string svg) =>
    Regex.Replace(svg, @"-?\d+(\.\d+)?(e-?\d+)?", m =>
    {
        var value = Math.Round(double.Parse(m.Value, CultureInfo.InvariantCulture), 2);
        return (value == 0 ? 0 : value).ToString("0.##", CultureInfo.InvariantCulture);
    });

static float Number(string text) => float.Parse(text, CultureInfo.InvariantCulture);

static string Hash(string text) => Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes(text)))[..16];

static string FindRoot(string from)
{
    for (var directory = new DirectoryInfo(from); directory is not null; directory = directory.Parent)
    {
        if (File.Exists(Path.Combine(directory.FullName, "Mindweave.slnx")))
        {
            return directory.FullName;
        }
    }

    throw new DirectoryNotFoundException("Run from inside the Mindweave repository.");
}
