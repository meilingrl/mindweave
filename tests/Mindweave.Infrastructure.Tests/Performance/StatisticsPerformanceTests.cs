using System.Diagnostics;
using Mindweave.Application.Statistics;
using Mindweave.Core.Workspaces;
using Mindweave.Infrastructure.Sqlite;
using Mindweave.Infrastructure.Tests.Chat;
using Mindweave.Testing;

namespace Mindweave.Infrastructure.Tests.Performance;

/// <summary>
/// The statistics page's load on a large database (2026-11-12): a heavy year and more of use, read with the aggregate
/// queries. The full-size run is opt-in (MINDWEAVE_PERF=1, as the other storage budgets); the smoke run keeps the
/// generator and the measured path working on every pass and asserts nothing about time.
/// </summary>
public class StatisticsPerformanceTests
{
    /// <summary>One whole page load (usage for the period and every activity fact): "well under a second".</summary>
    private static readonly TimeSpan LoadBudget = PerfBudget.Ms(500);

    private static CancellationToken Ct => TestContext.Current.CancellationToken;

    [Fact]
    public Task Smoke() => RunAsync(new Shape(Conversations: 40, MessagesPerConversation: 10, Requests: 400, Summaries: 10, Branches: 10), enforceBudget: false);

    [Fact]
    [Trait("Category", "Performance")]
    public Task Statistics_of_a_large_database_load_within_budget()
    {
        Assert.SkipUnless(Environment.GetEnvironmentVariable("MINDWEAVE_PERF") == "1", "Run through scripts/perf.sh.");
        return RunAsync(new Shape(Conversations: 2_000, MessagesPerConversation: 25, Requests: 20_000, Summaries: 300, Branches: 500), enforceBudget: true);
    }

    /// <summary>
    /// 50,000 messages (half questions) in 2,000 conversations over two workspaces, 20,000 requests over 400 days in three
    /// models and every purpose, 300 summaries and 500 branches, generated by recursive SQL in one transaction.
    /// </summary>
    private sealed record Shape(int Conversations, int MessagesPerConversation, int Requests, int Summaries, int Branches);

    private static async Task RunAsync(Shape shape, bool enforceBudget)
    {
        await using var h = await ChatHarness.StartAsync(configure: false);
        var now = new DateTimeOffset(2026, 11, 12, 10, 0, 0, TimeSpan.FromHours(8));
        var other = await new Testing.Usage.UsageSeed(h.Database).WorkspaceAsync("第二个", now.AddDays(-500));
        var seeding = Stopwatch.StartNew();
        await FillAsync(h, other, shape, now);
        seeding.Stop();

        var service = new UsageStatisticsService(
            new SqliteStatisticsStore(h.Database), h.Settings, TimeProvider.System,
            new UsageStatisticsOptions { Time = new ManualTime(now), Zone = Statistics.UsageStatisticsTests.Berlin });
        var messages = shape.Conversations * shape.MessagesPerConversation;
        var all = await MedianAsync(async () =>
        {
            var report = await service.LoadAsync(null, UsagePeriod.Daily, Ct);
            Assert.Equal(messages / 2, report.Activity.Questions);
            Assert.Equal(shape.Requests, report.Usage.RequestsEver);
        });
        var monthly = await MedianAsync(async () => Assert.Equal(12, (await service.LoadAsync(null, UsagePeriod.Monthly, Ct)).Usage.Buckets.Count));
        var scoped = await MedianAsync(async () => Assert.True((await service.LoadAsync(h.Workspace, UsagePeriod.Monthly, Ct)).Activity.Questions > 0));

        TestContext.Current.TestOutputHelper?.WriteLine(
            $"{shape}: seed {seeding.ElapsedMilliseconds} ms, all/daily {all.TotalMilliseconds:F1} ms, all/monthly {monthly.TotalMilliseconds:F1} ms, workspace/monthly {scoped.TotalMilliseconds:F1} ms");
        if (enforceBudget)
        {
            foreach (var (name, took) in new[] { ("all workspaces, by day", all), ("all workspaces, by month", monthly), ("one workspace, by month", scoped) })
            {
                Assert.True(took <= LoadBudget, $"Loading the statistics ({name}) took {took.TotalMilliseconds:F1} ms (budget {LoadBudget.TotalMilliseconds} ms).");
            }
        }
    }

    private static Task<int> FillAsync(ChatHarness h, WorkspaceId other, Shape shape, DateTimeOffset now)
    {
        var messages = shape.Conversations * shape.MessagesPerConversation;
        var start = now.AddDays(-400).ToUnixTimeMilliseconds();
        var messageStep = (now.ToUnixTimeMilliseconds() - start) / messages;
        var requestStep = (now.ToUnixTimeMilliseconds() - start) / shape.Requests;
        return h.Database.WriteAsync(
            (c, t) =>
            {
                (string, object?)[] common =
                [
                    ("$w1", h.Workspace.ToString()), ("$w2", other.ToString()), ("$start", start), ("$mstep", messageStep), ("$rstep", requestStep),
                    ("$conversations", shape.Conversations), ("$per", shape.MessagesPerConversation), ("$messages", messages),
                    ("$requests", shape.Requests), ("$summaries", shape.Summaries), ("$branches", shape.Branches),
                ];
                c.Execute(t, """
                    WITH RECURSIVE n(i) AS (SELECT 0 UNION ALL SELECT i + 1 FROM n WHERE i < $conversations - 1)
                    INSERT INTO conversation (id, workspace_id, title, title_source, created_at, updated_at)
                    SELECT printf('c-%08d', i), CASE WHEN i % 2 = 0 THEN $w1 ELSE $w2 END, '会话', 'manual', $start + i * $per * $mstep, $start
                    FROM n;
                    """, common);
                c.Execute(t, """
                    WITH RECURSIVE n(i) AS (SELECT 0 UNION ALL SELECT i + 1 FROM n WHERE i < $messages - 1)
                    INSERT INTO message (id, conversation_id, seq, role, state, created_at, completed_at)
                    SELECT printf('m-%08d', i), printf('c-%08d', i / $per), i % $per, CASE WHEN i % 2 = 0 THEN 'user' ELSE 'assistant' END,
                           'complete', $start + i * $mstep, $start + i * $mstep
                    FROM n;
                    """, common);
                c.Execute(t, """
                    WITH RECURSIVE n(i) AS (SELECT 0 UNION ALL SELECT i + 1 FROM n WHERE i < $branches - 1)
                    INSERT INTO branch_source (child_id, parent_id, source_message_id, source_block, quote, anchor, anchor_version, render_profile, created_at)
                    SELECT printf('c-%08d', $conversations - 1 - i), printf('c-%08d', i), printf('m-%08d', i * $per + 1), 0, '引用', '{}', 1, 'perf', $start
                    FROM n;
                    """, common);
                c.Execute(t, """
                    WITH RECURSIVE n(i) AS (SELECT 0 UNION ALL SELECT i + 1 FROM n WHERE i < $requests - 1)
                    INSERT INTO generation_task (id, kind, conversation_id, target_message_id, state, model_config_id, base_url, protocol, model,
                                                 credential_ref, input_message_ids, created_at, summary_to_seq)
                    SELECT printf('t-%08d', i),
                           CASE i % 4 WHEN 0 THEN 'answer' WHEN 1 THEN 'answer' WHEN 2 THEN 'title' ELSE 'summary' END,
                           printf('c-%08d', i % $conversations),
                           CASE WHEN i % 4 < 2 THEN printf('m-%08d', (i % $conversations) * $per + 1) END,
                           'completed', 'perf',
                           CASE i % 3 WHEN 0 THEN 'https://api.deepseek.com' WHEN 1 THEN 'https://open.bigmodel.cn/api/paas/v4' ELSE 'https://relay.example.org/v1' END,
                           'chat_completions',
                           CASE i % 3 WHEN 0 THEN 'deepseek-flash' WHEN 1 THEN 'glm-5' ELSE 'claude-sonnet' END,
                           'perf/key', '[]', $start + i * $rstep, 0
                    FROM n WHERE i % 10 <> 9;
                    """, common);
                c.Execute(t, """
                    WITH RECURSIVE n(i) AS (SELECT 0 UNION ALL SELECT i + 1 FROM n WHERE i < $requests - 1)
                    INSERT INTO ai_request (id, task_id, workspace_id, kind, model, base_url, started_at, finished_at, outcome, output_chars,
                                            prompt_tokens, completion_tokens, estimated_tokens)
                    SELECT printf('r-%08d', i),
                           CASE WHEN i % 10 <> 9 THEN printf('t-%08d', i) END,
                           CASE WHEN i % 10 = 9 THEN CASE WHEN i % 20 = 9 THEN $w1 ELSE $w2 END END,
                           CASE WHEN i % 10 = 9 THEN 'workspace-name' END,
                           CASE WHEN i % 10 = 9 THEN 'deepseek-flash' END,
                           CASE WHEN i % 10 = 9 THEN 'https://api.deepseek.com' END,
                           $start + i * $rstep, $start + i * $rstep + 1500,
                           CASE WHEN i % 50 = 7 THEN 'failed' ELSE 'completed' END, 400,
                           CASE WHEN i % 25 = 3 THEN NULL ELSE 800 + i % 3000 END,
                           CASE WHEN i % 25 = 3 THEN NULL ELSE 200 + i % 900 END,
                           900
                    FROM n;
                    """, common);
                c.Execute(t, """
                    WITH RECURSIVE n(i) AS (SELECT 0 UNION ALL SELECT i + 1 FROM n WHERE i < $summaries - 1)
                    INSERT INTO summary_node (id, workspace_id, conversation_id, current_version_id, base_title, display_name, name_source, created_at, updated_at)
                    SELECT printf('n-%08d', i), CASE WHEN i % 2 = 0 THEN $w1 ELSE $w2 END, printf('c-%08d', i), printf('v-%08d', i), '总结', '总结', 'base',
                           $start + i * $rstep * 50, $start
                    FROM n;
                    """, common);
                c.Execute(t, """
                    WITH RECURSIVE n(i) AS (SELECT 0 UNION ALL SELECT i + 1 FROM n WHERE i < $summaries - 1)
                    INSERT INTO summary_version (id, node_id, seq, title, body, to_seq, origin, created_at)
                    SELECT printf('v-%08d', i), printf('n-%08d', i), 1, '总结', '正文', 0, 'generated', $start FROM n;
                    """, common);
                c.Execute(t, """
                    INSERT INTO summary_read_state (version_id, read_source, max_progress, updated_at)
                    SELECT id, 'progress', 1, $start FROM summary_version WHERE rowid % 3 = 0;
                    """, common);
                return 0;
            },
            CancellationToken.None);
    }

    /// <summary>One warm-up, then the median of five runs.</summary>
    private static async Task<TimeSpan> MedianAsync(Func<Task> action)
    {
        await action();
        var samples = new List<TimeSpan>();
        for (var i = 0; i < 5; i++)
        {
            var watch = Stopwatch.StartNew();
            await action();
            samples.Add(watch.Elapsed);
        }

        return samples.Order().ElementAt(samples.Count / 2);
    }
}
